/**
 * Draw a pixel sprite to a canvas
 * @param {HTMLCanvasElement} canvas
 * @param {number[][]} spriteData - 2D array of color indices
 * @param {number} scale - pixels per sprite pixel
 * @param {boolean} [clearBg=false] - fill background
 */
function drawAvatarSprite(canvas, spriteData, scale = 6, clearBg = false) {
  if (!canvas) return;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;

  const h = spriteData.length;
  const w = spriteData[0].length;
  canvas.width = w * scale;
  canvas.height = h * scale;

  if (clearBg) {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
  }

  spriteData.forEach((row, y) => {
    row.forEach((cell, x) => {
      const color = AV_COLORS[cell];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(x * scale, y * scale, scale, scale);
      }
    });
  });
}

// Animated walk cycle (legs alternate)
function drawWalkFrame(canvas, frame, scale = 4) {
  if (!canvas) return;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;

  const w = AVATAR_WALK[0].length;
  const h = AVATAR_WALK.length;
  canvas.width = w * scale;
  canvas.height = h * scale;
  ctx.clearRect(0, 0, canvas.width, canvas.height);

  // Draw body
  AVATAR_WALK.forEach((row, y) => {
    row.forEach((cell, x) => {
      const color = AV_COLORS[cell];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(x * scale, y * scale, scale, scale);
      }
    });
  });

  // Animate legs based on frame
  const legCycle = Math.floor(frame / 8) % 4;
  const legColor = AV_COLORS[10];
  ctx.fillStyle = legColor;

  if (legCycle === 0) {
    ctx.fillRect(4 * scale, 14 * scale, scale, 2 * scale);
    ctx.fillRect(9 * scale, 13 * scale, scale, 2 * scale);
  } else if (legCycle === 1) {
    ctx.fillRect(4 * scale, 13 * scale, scale, 2 * scale);
    ctx.fillRect(9 * scale, 14 * scale, scale, 2 * scale);
  } else if (legCycle === 2) {
    ctx.fillRect(4 * scale, 14 * scale, scale, 2 * scale);
    ctx.fillRect(9 * scale, 13 * scale, scale, 2 * scale);
  } else {
    ctx.fillRect(4 * scale, 13 * scale, scale, 2 * scale);
    ctx.fillRect(9 * scale, 14 * scale, scale, 2 * scale);
  }
}

